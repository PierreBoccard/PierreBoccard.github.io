    function buildScene(scrolly) {
        var svg = scrolly.querySelector('.radec-scene');
        if (!svg) return null;
        var rng = mulberry32(20260524);

        /* ----- Panel frames + labels ----- */
        var framesG = svgEl('g', { 'class': 'radec-frames' });
        framesG.appendChild(svgEl('rect', {
            x: L.x, y: L.y, width: L.w, height: L.h, 'class': 'radec-frame'
        }));
        framesG.appendChild(svgEl('rect', {
            x: R.x, y: R.y, width: R.w, height: R.h, 'class': 'radec-frame'
        }));
        /* Static panel title */
        var lt = svgEl('text', {
            x: L.x + L.w / 2, y: L.y - 35,
            'class': 'radec-panel-title', 'text-anchor': 'middle'
        });
        lt.textContent = 'RA  *  Dec   (sky projection)';
        framesG.appendChild(lt);
        var lt2 = svgEl('text', {
            x: L.x + L.w / 2, y: L.y - 12,
            'class': 'radec-panel-sub radec-panel-sub-static', 'text-anchor': 'middle'
        });
        lt2.textContent = 'unchanged by photo-z';
        framesG.appendChild(lt2);

        var rt = svgEl('text', {
            x: R.x + R.w / 2, y: R.y - 35,
            'class': 'radec-panel-title', 'text-anchor': 'middle'
        });
        rt.textContent = 'RA  *  redshift  (LOS slice)';
        framesG.appendChild(rt);
        var rt2 = svgEl('text', {
            x: R.x + R.w / 2, y: R.y - 12,
            'class': 'radec-panel-sub radec-panel-sub-shuffle', 'text-anchor': 'middle'
        });
        rt2.textContent = 'scrambled by photo-z';
        framesG.appendChild(rt2);

        /* Axis labels under the panels */
        function axisLabel(panel, txt) {
            var t = svgEl('text', {
                x: panel.x + panel.w / 2, y: panel.y + panel.h + 28,
                'class': 'radec-axis-label', 'text-anchor': 'middle'
            });
            t.textContent = txt;
            framesG.appendChild(t);
        }
        axisLabel(L, 'sky longitude  RA  ->');
        axisLabel(R, 'sky longitude  RA  ->');

        /* y-axis labels (rotated) */
        function yLabel(panel, txt) {
            var t = svgEl('text', {
                x: panel.x - 28, y: panel.y + panel.h / 2,
                'class': 'radec-axis-label', 'text-anchor': 'middle',
                transform: 'rotate(-90 ' + (panel.x - 28) + ' ' + (panel.y + panel.h / 2) + ')'
            });
            t.textContent = txt;
            framesG.appendChild(t);
        }
        yLabel(L, 'sky latitude  Dec');
        yLabel(R, 'redshift  z  (line of sight)');

        svg.appendChild(framesG);

        /* ----- Generate galaxies in BOTH panels ----- */
        /* Reference: 1000 wide, ~543 tall. Scale x to panel.w / 1000 and y to
           panel.h / refH. Same scale used for both panels. */
        var REF_W = 1000;
        var REF_H = 543;

        var galaxiesG = svgEl('g', { 'class': 'radec-galaxies' });
        var galaxies = [];

        for (var i = 0; i < GALAXY_REF.length; i++) {
            var pp = GALAXY_REF[i];
            var fx = pp[0] / REF_W;
            var fy = pp[1] / REF_H;

            var noise = gaussian(rng);
            var color = GALAXY_COLOURS[Math.floor(rng() * GALAXY_COLOURS.length)];
            var r = 1.1 + rng() * 1.3;
            var alpha = 0.5 + rng() * 0.4;

            /* LEFT panel galaxy (static) */
            var lcx = L.x + fx * L.w;
            var lcy = L.y + fy * L.h;
            var leftEl = svgEl('circle', {
                cx: lcx.toFixed(1), cy: lcy.toFixed(1),
                r: r.toFixed(2),
                fill: color,
                'class': 'radec-galaxy radec-galaxy-left'
            });
            leftEl.style.opacity = alpha;
            galaxiesG.appendChild(leftEl);

            /* RIGHT panel galaxy (shuffles in y) */
            var rcx = R.x + fx * R.w;
            var rcy = R.y + fy * R.h;
            var rightEl = svgEl('circle', {
                cx: rcx.toFixed(1), cy: rcy.toFixed(1),
                r: r.toFixed(2),
                fill: color,
                'class': 'radec-galaxy radec-galaxy-right'
            });
            rightEl.style.opacity = alpha;
            galaxiesG.appendChild(rightEl);

            galaxies.push({
                rightEl: rightEl,
                trueY:   rcy,
                noise:   noise
            });
        }

        svg.appendChild(galaxiesG);

        return { svg: svg, galaxies: galaxies };
    }

    /* ===================================================================== */
    /* Progress -> right panel y shuffle                                     */
    /* ===================================================================== */

    function applyProgress(state, progress, opts) {
        if (!state) return;
        progress = clamp(progress, 0, 1);
        var p = progress * progress * (3 - 2 * progress);

        for (var i = 0; i < state.galaxies.length; i++) {
            var g = state.galaxies[i];
            var dy = p * MAX_LOS_SHIFT_PX * g.noise;
            var newY = g.trueY + dy;
            if (newY < R.y) newY = R.y;
            else if (newY > R.y + R.h) newY = R.y + R.h;
            g.rightEl.setAttribute('cy', newY.toFixed(1));
        }

        if (opts) {
            if (opts.hudBar) opts.hudBar.style.width = (progress * 100).toFixed(1) + '%';
            if (opts.hudSigma) {
                var sig = (SIGMA_Z_MAX * progress).toFixed(3);
                opts.hudSigma.textContent = 'σₙ = ' + sig;
            }
            if (opts.hudSmear) {
                var smearMpc = Math.round(SIGMA_Z_MAX * progress * 3100);
                opts.hudSmear.textContent = '≈ ' + smearMpc + ' Mpc/h smear';
            }
        }
    }

    /* ===================================================================== */
    /* Init                                                                  */
    /* ===================================================================== */

    function init() {
        var scrolly = document.getElementById('radecScrolly');
        if (!scrolly) return;
        var state = buildScene(scrolly);
        var hudBar    = scrolly.querySelector('.scrolly-progress-bar');
        var hudSigma  = scrolly.querySelector('.scrolly-progress-label .sigma');
        var hudSmear  = scrolly.querySelector('.scrolly-progress-label .smear');

        function update() {
            var rect = scrolly.getBoundingClientRect();
            var vh = window.innerHeight;
            var total = scrolly.offsetHeight - vh;
            if (total <= 0) {
                applyProgress(state, 0, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });
                return;
            }
            var scrolled = -rect.top;
            var pp = clamp(scrolled / total, 0, 1);
            applyProgress(state, pp, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });
        }

        applyProgress(state, 0, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });

        var ticking = false;
        window.addEventListener('scroll', function () {
            if (ticking) return;
            window.requestAnimationFrame(function () { update(); ticking = false; });
            ticking = true;
        }, { passive: true });
        window.addEventListener('resize', update, { passive: true });

        scrolly.classList.add('is-ready');
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
