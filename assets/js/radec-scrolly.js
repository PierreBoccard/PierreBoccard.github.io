    function buildScene(scrolly) {
        var svg = scrolly.querySelector('.radec-scene');
        if (!svg) return null;
        var rng = mulberry32(20260525);

        /* ----- Panel frames + labels ----- */
        var framesG = svgEl('g', { 'class': 'radec-frames' });
        framesG.appendChild(svgEl('rect', {
            x: L.x, y: L.y, width: L.w, height: L.h, 'class': 'radec-frame'
        }));
        framesG.appendChild(svgEl('rect', {
            x: R.x, y: R.y, width: R.w, height: R.h, 'class': 'radec-frame'
        }));

        var lt = svgEl('text', {
            x: L.x + L.w / 2, y: L.y - 35,
            'class': 'radec-panel-title', 'text-anchor': 'middle'
        });
        lt.textContent = 'TRUE-Z SLICE   (spec-z, no photo-z error)';
        framesG.appendChild(lt);
        var lt2 = svgEl('text', {
            x: L.x + L.w / 2, y: L.y - 12,
            'class': 'radec-panel-sub radec-panel-sub-static', 'text-anchor': 'middle'
        });
        lt2.textContent = '~' + SLICE_MPC + ' Mpc/h thick';
        framesG.appendChild(lt2);

        var rt = svgEl('text', {
            x: R.x + R.w / 2, y: R.y - 35,
            'class': 'radec-panel-title', 'text-anchor': 'middle'
        });
        rt.textContent = 'PHOTO-Z SLICE   (same window, perturbed z)';
        framesG.appendChild(rt);
        var rt2 = svgEl('text', {
            x: R.x + R.w / 2, y: R.y - 12,
            'class': 'radec-panel-sub radec-panel-sub-shuffle', 'text-anchor': 'middle'
        });
        rt2.textContent = 'σ_z(1+z) reshuffles which galaxies fall in / out';
        framesG.appendChild(rt2);

        function axisLabel(panel, txt) {
            var t = svgEl('text', {
                x: panel.x + panel.w / 2, y: panel.y + panel.h + 28,
                'class': 'radec-axis-label', 'text-anchor': 'middle'
            });
            t.textContent = txt;
            framesG.appendChild(t);
        }
        axisLabel(L, 'right ascension  RA  [deg]');
        axisLabel(R, 'right ascension  RA  [deg]');

        function yLabel(panel, txt) {
            var t = svgEl('text', {
                x: panel.x - 28, y: panel.y + panel.h / 2,
                'class': 'radec-axis-label', 'text-anchor': 'middle',
                transform: 'rotate(-90 ' + (panel.x - 28) + ' ' + (panel.y + panel.h / 2) + ')'
            });
            t.textContent = txt;
            framesG.appendChild(t);
        }
        yLabel(L, 'declination  Dec  [deg]');
        yLabel(R, 'declination  Dec  [deg]');

        svg.appendChild(framesG);

        /* ----- LEFT panel galaxies (true-z slice, static) ----- */
        var leftG = svgEl('g', { 'class': 'radec-galaxies radec-left' });
        for (var i = 0; i < TRUE_RADEC.length; i++) {
            var p = TRUE_RADEC[i];
            var xy = radecToPanel(p[0], p[1], L);
            var color = GALAXY_COLOURS[Math.floor(rng() * GALAXY_COLOURS.length)];
            var r = 1.1 + rng() * 1.3;
            var alpha = 0.55 + rng() * 0.40;
            var c = svgEl('circle', {
                cx: xy[0].toFixed(1), cy: xy[1].toFixed(1),
                r: r.toFixed(2),
                fill: color,
                'class': 'radec-galaxy'
            });
            c.style.opacity = alpha;
            leftG.appendChild(c);
        }
        svg.appendChild(leftG);

        /* ----- RIGHT panel: two layers, true-z then phot-z (cross-fade) -- */
        var trueLayer = svgEl('g', { 'class': 'radec-galaxies radec-true-layer' });
        var trueAlphas = [];
        for (var j = 0; j < TRUE_RADEC.length; j++) {
            var pp = TRUE_RADEC[j];
            var xy2 = radecToPanel(pp[0], pp[1], R);
            var col2 = GALAXY_COLOURS[Math.floor(rng() * GALAXY_COLOURS.length)];
            var rr2 = 1.1 + rng() * 1.3;
            var a2 = 0.55 + rng() * 0.40;
            var c2 = svgEl('circle', {
                cx: xy2[0].toFixed(1), cy: xy2[1].toFixed(1),
                r: rr2.toFixed(2),
                fill: col2,
                'class': 'radec-galaxy'
            });
            c2.style.opacity = a2;
            trueLayer.appendChild(c2);
            trueAlphas.push(a2);
        }

        var photLayer = svgEl('g', { 'class': 'radec-galaxies radec-phot-layer' });
        var photAlphas = [];
        for (var k = 0; k < PHOT_RADEC.length; k++) {
            var ppp = PHOT_RADEC[k];
            var xy3 = radecToPanel(ppp[0], ppp[1], R);
            var col3 = GALAXY_COLOURS[Math.floor(rng() * GALAXY_COLOURS.length)];
            var rr3 = 1.1 + rng() * 1.3;
            var a3 = 0.55 + rng() * 0.40;
            var c3 = svgEl('circle', {
                cx: xy3[0].toFixed(1), cy: xy3[1].toFixed(1),
                r: rr3.toFixed(2),
                fill: col3,
                'class': 'radec-galaxy'
            });
            c3.style.opacity = 0;       /* starts hidden */
            photLayer.appendChild(c3);
            photAlphas.push(a3);
        }
        svg.appendChild(trueLayer);
        svg.appendChild(photLayer);

        return {
            svg: svg,
            trueLayer: trueLayer,
            photLayer: photLayer,
            trueAlphas: trueAlphas,
            photAlphas: photAlphas
        };
    }

    /* =================================================================== */
    /* Progress -> right-panel cross-fade                                  */
    /* =================================================================== */

    function applyProgress(state, progress, opts) {
        if (!state) return;
        progress = clamp(progress, 0, 1);
        /* Ease so the transition feels intentional */
        var p = progress * progress * (3 - 2 * progress);

        /* Cross-fade: true layer 1 -> 0,  phot layer 0 -> 1 */
        var trueOpacity = 1 - p;
        var photOpacity = p;

        var trueCircles = state.trueLayer.children;
        for (var i = 0; i < trueCircles.length; i++) {
            trueCircles[i].style.opacity = (state.trueAlphas[i] * trueOpacity).toFixed(3);
        }
        var photCircles = state.photLayer.children;
        for (var j = 0; j < photCircles.length; j++) {
            photCircles[j].style.opacity = (state.photAlphas[j] * photOpacity).toFixed(3);
        }

        if (opts) {
            if (opts.hudBar) opts.hudBar.style.width = (progress * 100).toFixed(1) + '%';
            if (opts.hudSigma) {
                var sig = (SIGMA_Z * progress).toFixed(3);
                opts.hudSigma.textContent = 'σₙ = ' + sig + ' (1+z)';
            }
            if (opts.hudSmear) {
                var fracIn = Math.round((1 - p) * 100);
                opts.hudSmear.textContent = fracIn + '% of the true-z galaxies still in slice';
            }
        }
    }

    /* =================================================================== */
    /* Init                                                                */
    /* =================================================================== */

    function init() {
        var scrolly = document.getElementById('radecScrolly');
        if (!scrolly) return;
        var state = buildScene(scrolly);
        var hudBar    = scrolly.querySelector('.scrolly-progress-bar');
        var hudSigma  = scrolly.querySelector('.scrolly-progress-label .sigma');
        var hudSmear  = scrolly.querySelector('.scrolly-progress-label .smear');

        function update() {
            var rect = scrolly.getBoundingClientRect();
            var vh = window.innerHeight;
            var total = scrolly.offsetHeight - vh;
            if (total <= 0) {
                applyProgress(state, 0, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });
                return;
            }
            var scrolled = -rect.top;
            var pp = clamp(scrolled / total, 0, 1);
            applyProgress(state, pp, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });
        }

        applyProgress(state, 0, { hudBar: hudBar, hudSigma: hudSigma, hudSmear: hudSmear });

        var ticking = false;
        window.addEventListener('scroll', function () {
            if (ticking) return;
            window.requestAnimationFrame(function () { update(); ticking = false; });
            ticking = true;
        }, { passive: true });
        window.addEventListener('resize', update, { passive: true });

        scrolly.classList.add('is-ready');
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
